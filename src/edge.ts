// Per-instance Caddy edge for remote backends: one loopback listener per browser-facing upstream host.
// It forwards unchanged over HTTPS (upstream Host + SNI), answers CORS for the instance's own origins, strips Origin upstream.
import { EDGE_OFFSETS, hostPort } from "./offsets";

export const EDGE_IMAGE = "caddy:2.10.2-alpine@sha256:4c6e91c6ed0e2fa03efd5b44747b625fec79bc9cd06ac5235a779726618e530d";

export type EdgeRoute = { key: string; port: number; upstream: string; host: string; keys: string[] };

const URL_RE = /^(https?|wss?):\/\//i;
export const edgeKey = (host: string) => `edge:${host}`;

// Distinct upstream hosts the FE env files name, in first-seen order; FE key lists say which var pointed where.
export function edgeUpstreams(envs: { fe: string; env: Record<string, string>; keys: string[] }[]): { host: string; upstream: string; keys: string[] }[] {
  const out = new Map<string, { host: string; upstream: string; keys: string[] }>();
  for (const { fe, env, keys } of envs) {
    for (const k of keys) {
      const v = env[k];
      if (!v || !URL_RE.test(v)) continue;
      const u = new URL(v.replace(/^ws/i, "http"));
      if (u.protocol !== "https:") throw new Error(`${fe} ${k}=${v}: the edge forwards to https upstreams only; use direct mode`);
      const e = out.get(u.host) ?? { host: u.host, upstream: `https://${u.host}`, keys: [] };
      e.keys.push(`${fe}:${k}`);
      out.set(u.host, e);
    }
  }
  return [...out.values()];
}

// Keeps ports an instance already holds for a host; new hosts take the next free edge offset of the slot.
export function edgeRoutes(slot: number, ups: ReturnType<typeof edgeUpstreams>, held: Record<string, number>): EdgeRoute[] {
  const taken = new Set(Object.entries(held).filter(([k]) => k.startsWith("edge:")).map(([, p]) => p));
  const free = EDGE_OFFSETS.map((o) => hostPort(slot, o)).filter((p) => !taken.has(p));
  return ups.map((u) => {
    const port = held[edgeKey(u.host)] ?? free.shift();
    if (!port) throw new Error(`more than ${EDGE_OFFSETS.length} upstream hosts for one instance`);
    return { key: edgeKey(u.host), port, ...u };
  });
}

// Points each URL var at its host's edge listener; path and query stay as written.
export function rewriteToEdge(env: Record<string, string>, keys: string[], routes: EdgeRoute[]): Record<string, string> {
  const out = { ...env };
  for (const k of keys) {
    const v = env[k];
    if (!v || !URL_RE.test(v)) continue;
    const ws = /^wss?:/i.test(v);
    const u = new URL(v.replace(/^ws/i, "http"));
    const r = routes.find((x) => x.host === u.host);
    if (!r) continue;
    out[k] = `${ws ? "ws" : "http"}://localhost:${r.port}${v.slice(v.toLowerCase().indexOf(u.host) + u.host.length)}`;
  }
  return out;
}

const reEsc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// Headers the browser may read on a cross-origin response (credentialed CORS cannot use "*").
const EXPOSE = "Content-Disposition, Content-Length, Content-Type, ETag, Location, Link, X-Request-Id, X-Total-Count";

export function caddyfile(routes: EdgeRoute[], origins: string[]): string {
  const allow = `^(${origins.map(reEsc).join("|")})$`;
  const blocks = routes.map((r) => `# ${r.keys.join(", ")}
http://:${r.port} {
	@preflight {
		method OPTIONS
		header_regexp Origin ${allow}
		header Access-Control-Request-Method *
	}
	handle @preflight {
		header {
			Access-Control-Allow-Origin {http.request.header.Origin}
			Access-Control-Allow-Credentials true
			Access-Control-Allow-Methods "GET, POST, PUT, PATCH, DELETE, OPTIONS"
			Access-Control-Allow-Headers {http.request.header.Access-Control-Request-Headers}
			Access-Control-Max-Age 600
			Vary "Origin, Access-Control-Request-Method, Access-Control-Request-Headers"
		}
		respond 204
	}
	@allowed header_regexp Origin ${allow}
	handle @allowed {
		reverse_proxy ${r.upstream} {
${upstreamOpts(r.host, "\t\t\t")}
			header_down Access-Control-Allow-Origin {http.request.header.Origin}
			header_down Access-Control-Allow-Credentials true
			header_down Access-Control-Expose-Headers ${JSON.stringify(EXPOSE)}
			header_down +Vary Origin
		}
	}
	handle {
		reverse_proxy ${r.upstream} {
${upstreamOpts(r.host, "\t\t\t")}
		}
	}
}
`);
  return `# generated by cosmos; do not edit
{
	admin off
	auto_https off
	persist_config off
}

${blocks.join("\n")}`;
}

// Upstream sees the request as sent to its own host: real Host and SNI, no Origin, no X-Forwarded-* added by the edge.
function upstreamOpts(host: string, ind: string): string {
  return [
    `header_up Host ${host}`,
    `header_up -Origin`,
    `header_up -X-Forwarded-For`,
    `header_up -X-Forwarded-Proto`,
    `header_up -X-Forwarded-Host`,
    `transport http {`,
    `\ttls_server_name ${host}`,
    `}`,
  ].map((l) => ind + l).join("\n");
}
